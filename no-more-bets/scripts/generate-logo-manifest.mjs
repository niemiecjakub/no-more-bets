/**
 * Scans public/clubs and public/leagues and writes lib/logo-manifest.gen.ts
 * so SlugIcon can request the correct extension once (no svg→png 404 chain).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

/** Prefer svg when both exist (one URL, vector default). */
function collectExtBySlug(dir) {
  /** @type {Map<string, 'svg' | 'png'>} */
  const map = new Map();
  if (!fs.existsSync(dir)) return map;
  for (const name of fs.readdirSync(dir)) {
    const m = name.match(/^(.+)\.(svg|png)$/i);
    if (!m) continue;
    const slug = m[1].toLowerCase();
    const ext = m[2].toLowerCase();
    if (ext !== "svg" && ext !== "png") continue;
    const prev = map.get(slug);
    if (!prev) {
      map.set(slug, ext);
      continue;
    }
    if (prev === "png" && ext === "svg") map.set(slug, "svg");
  }
  return map;
}

function mapToSortedRecord(map) {
  const obj = {};
  for (const key of [...map.keys()].sort()) {
    obj[key] = map.get(key);
  }
  return obj;
}

const clubsDir = path.join(root, "public", "clubs");
const leaguesDir = path.join(root, "public", "leagues");

const clubs = mapToSortedRecord(collectExtBySlug(clubsDir));
const leagues = mapToSortedRecord(collectExtBySlug(leaguesDir));

const outPath = path.join(root, "lib", "logo-manifest.gen.ts");
const body = `/** Generated by scripts/generate-logo-manifest.mjs — do not edit. */

export const clubLogoExtBySlug: Record<string, "svg" | "png"> = ${JSON.stringify(
  clubs,
  null,
  2
)};

export const leagueLogoExtBySlug: Record<string, "svg" | "png"> = ${JSON.stringify(
  leagues,
  null,
  2
)};
`;

fs.writeFileSync(outPath, body, "utf8");
console.log("Wrote", path.relative(root, outPath));
